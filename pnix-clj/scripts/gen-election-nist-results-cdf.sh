#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="${NIST_ELECTION_CDF_SRC:-$ROOT/ingest/election/nist-results-cdf}"
OUT="${NIST_ELECTION_CDF_OUT:-$ROOT/stdlib/lib/corpus/nist-election-results-cdf.generated.px}"
python3 - <<'PY' "$SRC" "$OUT"
import json,pathlib,re,sys,xml.etree.ElementTree as ET
src=pathlib.Path(sys.argv[1]); out=pathlib.Path(sys.argv[2]); receipt=json.loads((src/'source-receipt.json').read_text())
schema_files=[]; xsd_terms=[]; json_terms=[]
for meta in receipt.get('schema_files',[]):
    p=src/meta['path']; lower=p.name.lower(); row={k:meta[k] for k in ['repo_path','sha256','bytes']}
    row['kind']='json_schema' if lower.endswith('.json') or lower.endswith('.jsonschema') else 'xsd_schema'
    schema_files.append(row)
    if row['kind']=='json_schema':
        try:
            d=json.loads(p.read_text(errors='replace'))
            defs=d.get('definitions') or d.get('$defs') or {}
            props=d.get('properties') or {}
            for name,val in list(defs.items())[:500]:
                json_terms.append({'repo_path':meta['repo_path'],'term_kind':'definition','name':name,'type':val.get('type') if isinstance(val,dict) else None})
            for name,val in list(props.items())[:500]:
                json_terms.append({'repo_path':meta['repo_path'],'term_kind':'property','name':name,'type':val.get('type') if isinstance(val,dict) else None})
        except Exception as e:
            row['parse_error']=str(e)
    else:
        try:
            root=ET.parse(p).getroot()
            for el in root.iter():
                tag=el.tag.split('}',1)[-1]
                if tag in ('element','complexType','simpleType','attribute','group') and el.get('name'):
                    xsd_terms.append({'repo_path':meta['repo_path'],'term_kind':tag,'name':el.get('name'),'type':el.get('type')})
        except Exception as e:
            row['parse_error']=str(e)
def esc(s): s='' if s is None else str(s); return '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n')+'"'
def atom(v):
    if v is None: return 'null'
    if isinstance(v,bool): return 'true' if v else 'false'
    if isinstance(v,int): return str(v)
    if isinstance(v,str): return esc(v)
    if isinstance(v,list): return '[ ' + ' '.join(atom(x) for x in v) + ' ]'
    if isinstance(v,dict): return '{ ' + ' '.join(f'{k} = {atom(v[k])};' for k in sorted(v)) + ' }'
    raise TypeError(type(v))
seed={'schema':'election.nist_results_cdf.schema_metadata.v1','source':{'name':'NIST Election Results Reporting CDF schema metadata','license':'US-PD / NIST public schema metadata','retrieved_at_unix':receipt.get('retrieved_at_unix')},'summary':{'schema_file_count':len(schema_files),'xsd_term_count':len(xsd_terms),'json_term_count':len(json_terms),'election_results_ingested':False,'voter_records_ingested':False,'cast_vote_records_ingested':False,'spec_prose_ingested':False,'mirror_graph_wiring':False},'source_receipt':receipt,'schema_files':schema_files,'xsd_terms':xsd_terms[:2000],'json_terms':json_terms[:2000]}
out.parent.mkdir(parents=True,exist_ok=True); out.write_text('# GENERATED by scripts/gen-election-nist-results-cdf.sh; do not commit.\n'+atom(seed)+'\n')
print(f'generated {out}: schema_files={len(schema_files)}, xsd_terms={len(xsd_terms)}, json_terms={len(json_terms)}')
PY
