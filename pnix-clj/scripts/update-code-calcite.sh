#!/usr/bin/env bash
set -euo pipefail
ROOT="${PNIX_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
OUT_DIR="$ROOT/ingest/code/calcite"
VERSION="${CALCITE_VERSION:-1.42.0}"
BASE="https://repo1.maven.org/maven2/org/apache/calcite/calcite-core/$VERSION"
URL="${CALCITE_URL:-$BASE/calcite-core-$VERSION.jar}"
JAR="$OUT_DIR/calcite-core-$VERSION.jar"
TMP="$JAR.tmp.$$"
mkdir -p "$OUT_DIR/unpacked"
echo "download: $URL"
curl -fL --retry 3 --retry-delay 2 "$URL" -o "$TMP"
mv "$TMP" "$JAR"
shasum -a 256 "$JAR" > "$JAR.sha256"
rm -rf "$OUT_DIR/unpacked" && mkdir -p "$OUT_DIR/unpacked"
unzip -q "$JAR" -d "$OUT_DIR/unpacked"
{
  echo "source_url=$URL"
  echo "version=$VERSION"
  echo "retrieved_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "sha256=$(cut -d' ' -f1 "$JAR.sha256")"
} > "$JAR.meta"
echo "wrote: $JAR"
cat "$JAR.sha256"
