//! Self-hosting Codegen: MetaFx → Rust Source 생성
//!
//! Meta-circular Stage 2: pnix로 pnix의 meta 계층을 생성
//!
//! 규칙:
//! - 타입 정의만 생성 (인스턴스 데이터 ❌)
//! - std + serde만 의존
//! - core 타입 참조 ❌
//! - lowering / verify 호출 ❌

/// Self-hosting용 Rust 소스 생성: MetaFx IR 타입 정의를 Rust 소스 코드로 생성
///
/// meta_ir_gen.rs용으로 사용되며, MetaFxModule, MetaFxInput 등의 구조체 정의를 생성합니다.
///
/// ## 헌법 준수 (P0-1, C1)
///
/// 텍스트 생성만, 파일 I/O 없음
pub fn generate_meta_ir_source() -> String {
  let mut out = String::new();

  // 헤더
  out.push_str(HEADER);
  out.push('\n');

  // imports
  out.push_str("use serde::{Deserialize, Serialize};\n");
  out.push('\n');

  // MetaFxModule
  out.push_str(&generate_meta_fx_module_struct());
  out.push('\n');

  // MetaFxInput
  out.push_str(&generate_meta_fx_input_struct());
  out.push('\n');

  // MetaFxMorphismPort
  out.push_str(&generate_meta_fx_morphism_port_struct());
  out.push('\n');

  // MetaFxMorphism
  out.push_str(&generate_meta_fx_morphism_struct());
  out.push('\n');

  // MetaExecutionContract
  out.push_str(&generate_meta_execution_contract_struct());
  out.push('\n');

  // MetaFxNode
  out.push_str(&generate_meta_fx_node_struct());
  out.push('\n');

  // MetaFxPortInfo
  out.push_str(&generate_meta_fx_port_info_struct());
  out.push('\n');

  // MetaFxEdge
  out.push_str(&generate_meta_fx_edge_struct());
  out.push('\n');

  // MetaFxScope
  out.push_str(&generate_meta_fx_scope_struct());
  out.push('\n');

  // MetaFxStats
  out.push_str(&generate_meta_fx_stats_struct());

  out
}

const HEADER: &str = r#"// ============================================================
//  AUTO-GENERATED BY pnix (Stage 2: Partial Self-Hosting)
//  SOURCE OF TRUTH: pnix DSL
//  DO NOT EDIT MANUALLY
// ============================================================
"#;

fn generate_meta_fx_module_struct() -> String {
  r#"/// MetaFx 모듈: FxCore의 구조적 자기 기술 (Generated)
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct MetaFxModule {
    pub name: String,
    pub stage: u8,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub replay_hash: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub types: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub inputs: Vec<MetaFxInput>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub morphisms: Vec<MetaFxMorphism>,
    pub nodes: Vec<MetaFxNode>,
    pub edges: Vec<MetaFxEdge>,
    pub scopes: Vec<MetaFxScope>,
    pub stats: MetaFxStats,
}
"#
  .to_string()
}

