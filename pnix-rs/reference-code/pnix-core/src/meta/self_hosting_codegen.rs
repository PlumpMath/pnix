#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn meta_ir_source_contains_all_structs() {
    let source = generate_meta_ir_source();

    assert!(source.contains("pub struct MetaFxModule"));
    assert!(source.contains("pub struct MetaFxInput"));
    assert!(source.contains("pub struct MetaFxMorphism"));
    assert!(source.contains("pub struct MetaFxMorphismPort"));
    assert!(source.contains("pub struct MetaExecutionContract"));
    assert!(source.contains("pub struct MetaFxNode"));
    assert!(source.contains("pub struct MetaFxEdge"));
    assert!(source.contains("pub struct MetaFxPortInfo"));
    assert!(source.contains("pub struct MetaFxScope"));
    assert!(source.contains("pub struct MetaFxStats"));
  }

  #[test]
  fn meta_ir_source_contains_header() {
    let source = generate_meta_ir_source();

    assert!(source.contains("AUTO-GENERATED BY pnix"));
    assert!(source.contains("Stage 2: Partial Self-Hosting"));
    assert!(source.contains("DO NOT EDIT MANUALLY"));
  }

  #[test]
  fn generated_source_is_deterministic() {
    let source1 = generate_meta_ir_source();
    let source2 = generate_meta_ir_source();
    assert_eq!(source1, source2);
  }
}
