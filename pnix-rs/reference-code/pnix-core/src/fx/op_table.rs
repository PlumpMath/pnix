#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn test_op_zones() {
    assert_eq!(UnifiedMeaningOp::Add.zone(), EffectZone::Pure);
    assert_eq!(UnifiedMeaningOp::AtomNew.zone(), EffectZone::Stm);
  }

  #[test]
  fn test_op_signatures() {
    assert_eq!(UnifiedMeaningOp::Add.signature(), "Num → Num → Num");
  }

  #[test]
  fn test_op_laws() {
    let add_laws = UnifiedMeaningOp::Add.laws();
    assert!(add_laws.contains(&"commutative"));
    assert!(add_laws.contains(&"associative"));
  }

  #[test]
  fn test_op_ir_symbol() {
    assert_eq!(UnifiedMeaningOp::Add.ir_symbol(), "fx_Add");
    assert_eq!(UnifiedMeaningOp::AtomNew.ir_symbol(), "stm_atom_new");
  }

  #[test]
  fn test_op_arity() {
    assert_eq!(UnifiedMeaningOp::Add.arity(), 2);
    assert_eq!(UnifiedMeaningOp::AtomNew.arity(), 1);
  }

  #[test]
  fn test_all_ops() {
    let all = UnifiedMeaningOp::all();
    assert!(all.len() >= 3);
    assert!(all.contains(&UnifiedMeaningOp::Add));

    let meta = UnifiedMeaningOp::Add.meta();
    assert_eq!(meta.arity, 2);
    assert!(UnifiedMeaningOp::Add.is_optimizable());
  }

  #[test]
  fn test_op_from_str() {
    assert_eq!(
      UnifiedMeaningOp::from_str("Add"),
      Some(UnifiedMeaningOp::Add)
    );
    assert_eq!(UnifiedMeaningOp::from_str("Unknown"), None);
  }
}
