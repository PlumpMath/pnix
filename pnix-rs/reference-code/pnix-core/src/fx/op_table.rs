//! op_table! macro - Single source of truth for all semantic operations
//!
//! Generates:
//! - UnifiedMeaningOp enum with all operations
//! - Zone/signature/laws accessors
//! - IR symbol names for LLVM codegen
//!
//! ## 헌법 준수 (P0-1)
//!
//! - 구조 정의만 포함, 실행 코드 없음
//! - op_table! 매크로는 enum과 메서드만 생성
//! - 실제 연산 실행은 pnix-executor-graph에서 수행

use crate::effects::EffectZone;

/// 연산 메타데이터: op_table! 매크로에 의해 생성된 연산 메타데이터
///
/// ## 헌법 준수 (P0-1)
///
/// 구조 정의만, 값 계산 없음
#[derive(Debug, Clone)]
pub struct OpMeta {
  /// 효과 영역
  pub zone: EffectZone,
  /// 타입 시그니처 문자열
  pub signature: &'static str,
  /// 대수 법칙 목록
  pub laws: &'static [&'static str],
  /// IR 심볼 이름 (LLVM 코드 생성용)
  pub ir_symbol: &'static str,
  /// 인자 개수 (arity)
  pub arity: u8,
}

/// op_table! macro
///
/// Usage:
/// ```ignore
/// op_table! {
///     // Pure arithmetic
///     Add { zone: Pure, sig: "Int → Int → Int", laws: ["commutative", "associative"] }
///     Sub { zone: Pure, sig: "Int → Int → Int" }
///
///     // STM
///     AtomNew { zone: STM, sig: "a → Atom a" }
/// }
/// ```
#[macro_export]
macro_rules! op_table {
    // Main entry point
    (
        $(
            $name:ident {
                zone: $zone:ident
                $(, sig: $sig:literal)?
                $(, laws: [$($law:literal),* $(,)?])?
                $(, ir: $ir:literal)?
                $(, arity: $arity:literal)?
            }
        )*
    ) => {
        /// Unified MeaningOp enum (generated by op_table!)
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
        pub enum UnifiedMeaningOp {
            $($name,)*
        }

        impl UnifiedMeaningOp {
            /// Get effect zone
            pub fn zone(&self) -> $crate::effects::EffectZone {
                match self {
                    $(UnifiedMeaningOp::$name => $crate::effects::EffectZone::$zone,)*
                }
            }

            /// Get type signature
            pub fn signature(&self) -> &'static str {
                match self {
                    $(UnifiedMeaningOp::$name => op_table!(@sig $($sig)?),)*
                }
            }

            /// Get algebraic laws
            pub fn laws(&self) -> &'static [&'static str] {
                match self {
                    $(UnifiedMeaningOp::$name => op_table!(@laws $($($law),*)?),)*
                }
            }

            /// Get IR symbol for LLVM codegen
            pub fn ir_symbol(&self) -> &'static str {
                match self {
                    $(UnifiedMeaningOp::$name => op_table!(@ir $name $($ir)?),)*
                }
            }

            /// Get arity (number of arguments)
            pub fn arity(&self) -> u8 {
                match self {
                    $(UnifiedMeaningOp::$name => op_table!(@arity $($arity)?),)*
                }
            }

            /// Get full metadata
            pub fn meta(&self) -> $crate::fx::op_table::OpMeta {
                $crate::fx::op_table::OpMeta {
                    zone: self.zone(),
                    signature: self.signature(),
                    laws: self.laws(),
                    ir_symbol: self.ir_symbol(),
                    arity: self.arity(),
                }
            }

            /// Is this operation optimizable? (Pure zone)
            pub fn is_optimizable(&self) -> bool {
                matches!(
                    self.zone(),
                    EffectZone::Pure | EffectZone::Symbolic | EffectZone::Frp | EffectZone::Animation
                )
            }

            /// All operations
            pub fn all() -> &'static [UnifiedMeaningOp] {
                &[$(UnifiedMeaningOp::$name,)*]
            }

            /// Operation name as string
            pub fn name(&self) -> &'static str {
                match self {
                    $(UnifiedMeaningOp::$name => stringify!($name),)*
                }
            }

            /// Parse from string (convenience method)
            #[allow(clippy::should_implement_trait)]
            pub fn from_str(s: &str) -> Option<Self> {
                match s {
                    $(stringify!($name) => Some(UnifiedMeaningOp::$name),)*
                    _ => None,
                }
            }
        }

        /// Implement FromStr trait for UnifiedMeaningOp
        impl std::str::FromStr for UnifiedMeaningOp {
            type Err = String;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                match s {
                    $(stringify!($name) => Ok(UnifiedMeaningOp::$name),)*
                    _ => Err(format!("Unknown operation: {}", s)),
                }
            }
        }

        impl std::fmt::Display for UnifiedMeaningOp {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                write!(f, "{}", self.name())
            }
        }
    };

    // Helper: extract signature or default
    (@sig $sig:literal) => { $sig };
    (@sig) => { "" };

    // Helper: extract laws or empty
    (@laws $($law:literal),*) => { &[$($law),*] };
    (@laws) => { &[] };

    // Helper: extract IR symbol or generate from name
    (@ir $name:ident $ir:literal) => { $ir };
    (@ir $name:ident) => { concat!("fx_", stringify!($name)) };

    // Helper: extract arity or default to 0
    (@arity $arity:literal) => { $arity };
    (@arity) => { 0 };
}

