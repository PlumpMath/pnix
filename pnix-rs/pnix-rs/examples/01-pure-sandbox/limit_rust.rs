//! plain Rust의 한계 — 임의 코드를 "실행 전에 순수한가?"로 가둘 수단이 없다.
//!
//! Rust는 강타입·메모리안전 언어지만, 신뢰 경계 밖에서 온 *로직*을
//! (1) 실행 전에 순수성 판정하거나, (2) 효과(파일/네트워크/프로세스)를
//! 실행 전에 거부하거나, (3) 자원 상한을 강제하는 내장 수단이 없다.
//! 아래는 그 한계를 정직하게 보여준다(실제 파괴는 하지 않는다).

fn main() {
    // 부작용은 문법상 언제나 허용된다 — 컴파일러가 "순수해야 한다"를 강제하지 못한다.
    let mut side = Vec::new();
    side.push("나는 바깥을 건드렸다");
    println!("부작용 발생: {:?}", side);

    // 실제 위험(주석으로만): 아래는 문법상 유효하다 — plain Rust는 이걸 게이트하지 못한다.
    //   std::process::Command::new("sh").arg("-c").arg("rm -rf ~").status();
    //   std::fs::remove_file("/etc/passwd");
    println!("주의: std::process / std::fs 호출도 문법상 허용된다 (여기선 실행 안 함)");

    // "이 함수가 순수한가?"를 실행 전에 정적으로 판정하는 표준 수단이 없다.
    println!("plain Rust: 실행 전 순수성/효과 판정 게이트 없음");
}
