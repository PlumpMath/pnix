"""한계: 순진한 특화는 '가정'을 기록하지도, 가정이 깨졌을 때 재특화하지도 못한다.

값이 대개 고정(예: a=3, b=4)이라 가정하고 코드를 특화하면 빠르지만 — plain하게는
(1) 어떤 가정 하에 특화했는지 증거가 없고, (2) 나중에 값이 바뀌었는지(drift) 검사해
자동으로 재특화할 방법이 없다. 잘못된 가정으로 만든 코드를 조용히 계속 쓰게 된다.
"""
import os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
# a,b가 3,4라고 '가정'하고 특화(하드코딩)
def specialized(x):
    return 3 * x + 4          # a=3, b=4 를 박아넣음
print("가정 하 특화:", specialized(10))
# 그런데 a가 5로 바뀌면? — 이 함수는 그걸 모른 채 틀린 값을 계속 낸다
print("한계: 가정 기록도, drift 검사·자동 재특화도 없음 → 조용히 틀린다.")
