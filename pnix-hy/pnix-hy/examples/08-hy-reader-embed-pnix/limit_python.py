"""plain의 한계 — 다른 언어를 '읽는 시점(read-time)'에 1급으로 임베드할 수 없다.

Python에서 다른 언어 조각을 코드에 넣으려면 결국 '문자열'이다:
  cfg = "1 + 2"     # 그냥 문자열 — 읽는 시점에 파싱/투영되지 않고, 의미도 없다.
문자열을 실제로 쓰려면 런타임에 직접 파서를 호출해야 하고, 리더 단계에서 폼으로 승격되지 않는다.
Python엔 사용자 정의 reader macro가 없다.
"""
cfg = "1 + 2"  # 임베드된 다른-언어 코드는 그냥 불투명한 문자열이다
print("임베드 형태:", repr(cfg), "-> 읽는 시점엔 그냥 str (폼/의미 없음)")
print("Python: read-time에 폼으로 승격하는 사용자 reader macro = 없음")

print("\n결론: 다른 언어를 read-time에 폼으로 임베드/투영하는 1급 방법이 없다.")
