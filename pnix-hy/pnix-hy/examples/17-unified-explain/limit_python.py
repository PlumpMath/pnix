"""plain의 한계 — 한 계산을 '설명'하려면 여러 도구를 직접 조립해야 한다.

"이 코드의 값은? 순수한가? 안전 한계 안에서 도는가? 어디서 틀렸나? 실행 단면은?"에 답하려면
Python에선 eval + ast + dis + inspect + 예외처리 + (직접 만든) 자원제한을 각각 붙여야 하고,
그것들이 하나의 일관된 '설명' 레코드로 묶이지 않는다.
"""
src = "1 + 2"
value = eval(src)
print("값:", value)
print("순수성/안전한계/진단/실행단면을 '한 번에' 주는 통합 explain?: 없음")
print("-> eval, ast, dis, inspect, try/except, 자원제한을 각각 조립해야 한다")

print("\n결론: 값·순수성·안전성·진단·단면을 하나로 묶는 통합 설명 표면이 없다.")
