"""plain Python의 한계 — 코드/값의 '정본(canonical) 해시'가 없다.

Python에는:
  1) 문자열/객체의 hash()가 PYTHONHASHSEED로 실행마다 바뀌고(무염 불가),
  2) 코드(AST/소스)의 안정적 내용주소 해시를 표준으로 얻는 방법이 없으며,
  3) "무엇이 무엇으로부터 어떻게 달라졌는가(drift)"를 분류하는 표준이 없다.
"""
import ast

# 1) hash()는 무염(salt)되어 프로세스마다 값이 달라진다 -> 재현 불가.
print("hash('abc') =", hash("abc"), "(다른 프로세스에서 다시 실행하면 값이 달라진다)")

# 2) 코드의 '정본' 해시가 없다: ast.dump는 위치/속성이 섞여 정규화가 필요하고,
#    같은 의미의 코드라도 표현이 다르면 그대로는 비교가 안 된다.
a = ast.dump(ast.parse("a = 1"))
print("ast.dump 길이:", len(a), "(위치/속성 포함; '정본 내용해시'가 아니다)")

# 3) drift 분류 없음: 두 결과가 다를 때 '메타데이터만 다른지, 의미가 다른지'를
#    표준으로 알려주는 도구가 없다. 직접 만들어야 한다.
print("drift 분류: 표준 없음 (직접 구현 필요)")

print("\n결론: 재현성/감사(auditable)를 위한 '정본 해시 + drift 분류'가 기본 제공되지 않는다.")
